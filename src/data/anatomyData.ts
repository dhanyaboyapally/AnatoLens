export const STRUCTURE_MAP = new Map<string, AnatomicalStructure>(
  ANATOMY_STRUCTURES.map(s => [s.id, s])
)

export function findStructureByQuery(query: string): AnatomicalStructure | undefined {
  const q = query.toLowerCase()
  return ANATOMY_STRUCTURES.find(s =>
    s.id === q ||
    s.name.toLowerCase().includes(q) ||
    s.aliases.some(a => a.toLowerCase().includes(q)) ||
    s.latinName.toLowerCase().includes(q)
  )
}

export function getStructuresByCategory(category: string): AnatomicalStructure[] {
  return ANATOMY_STRUCTURES.filter(s => s.category === category)
}

export function getStructuresByRegion(region: string): AnatomicalStructure[] {
  return ANATOMY_STRUCTURES.filter(s => s.region === region)
}
